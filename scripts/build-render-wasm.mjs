import wabtFactory from 'wabt';
import {writeFile} from 'node:fs/promises';
const load=(ptr,offset)=>`(f32.load offset=${offset} (local.get $${ptr}))`;
const dot=row=>`(f32.add (f32.add (f32.add (f32.mul ${load('src',0)} ${load('mat',row*4)}) (f32.mul ${load('src',4)} ${load('mat',(row+4)*4)})) (f32.mul ${load('src',8)} ${load('mat',(row+8)*4)})) ${load('mat',(row+12)*4)})`;
const wat=`(module (memory (export "memory") 256 256)
(func (export "project") (param $src i32) (param $dst i32) (param $mat i32) (param $count i32)
(block $done (loop $next (br_if $done (i32.eqz (local.get $count)))
${[0,1,2,3].map(i=>`(f32.store offset=${i*4} (local.get $dst) ${dot(i)})`).join('\n')}
${[0,1,2].map(i=>`(f32.store offset=${16+i*4} (local.get $dst) ${load('src',12+i*4)})`).join('\n')}
(local.set $src (i32.add (local.get $src) (i32.const 24)))
(local.set $dst (i32.add (local.get $dst) (i32.const 28)))
(local.set $count (i32.sub (local.get $count) (i32.const 1))) (br $next)))))`;
const wabt=await wabtFactory(), module=wabt.parseWat('project.wat',wat);module.validate();
await writeFile(new URL('../shared/wasm/project.wat',import.meta.url),wat+'\n');
await writeFile(new URL('../shared/wasm/project.wasm',import.meta.url),module.toBinary({}).buffer);

await writeFile(new URL('../shared/wasm/project-bytes.js',import.meta.url),'// Generated by scripts/build-render-wasm.mjs; SPDX-License-Identifier: Apache-2.0\nexport default new Uint8Array('+JSON.stringify(Array.from(module.toBinary({}).buffer))+');\n');
